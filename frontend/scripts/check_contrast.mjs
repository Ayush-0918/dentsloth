#!/usr/bin/env node
// DentSloth – WCAG AA contrast checker over design token pairs
// Run: node scripts/check_contrast.mjs
// Writes: docs/contrast.md

import { writeFileSync, mkdirSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))

// ── Token values (must match tokens.css) ──────────────────────────────────────
const TOKENS = {
  // Light theme
  bg:          '#DDE3E8',
  surface:     '#EDF0F3',
  surface2:    '#F5F6F8',
  ink:         '#3A0F34',
  inkMuted:    'rgba(58,15,52,0.62)',   // ~#7B5F78 on bg
  accent:      '#EAAA00',
  ok:          '#2D6B3C',
  warn:        '#85550A',
  danger:      '#8B1A1A',
  onAccent:    '#3A0F34',
  // Dark theme
  dark_bg:     '#26092A',
  dark_ink:    '#DDE3E8',
  dark_surface:'#321240',
}

// ── Hex to sRGB ───────────────────────────────────────────────────────────────
function hexToRgb(hex) {
  hex = hex.replace('#','')
  if (hex.length === 3) hex = hex.split('').map(c=>c+c).join('')
  return {
    r: parseInt(hex.slice(0,2),16)/255,
    g: parseInt(hex.slice(2,4),16)/255,
    b: parseInt(hex.slice(4,6),16)/255
  }
}

function linearize(c) {
  return c <= 0.04045 ? c/12.92 : Math.pow((c+0.055)/1.055, 2.4)
}

function luminance({r,g,b}) {
  return 0.2126*linearize(r) + 0.7152*linearize(g) + 0.0722*linearize(b)
}

function contrast(hex1, hex2) {
  const L1 = luminance(hexToRgb(hex1))
  const L2 = luminance(hexToRgb(hex2))
  const lighter = Math.max(L1,L2), darker = Math.min(L1,L2)
  return (lighter+0.05)/(darker+0.05)
}

function blendOnBg(rgba, bg) {
  // very rough: parse rgba and blend with bg
  const m = rgba.match(/rgba?\((\d+),(\d+),(\d+),?([\d.]+)?\)/)
  if (!m) return rgba
  const a = parseFloat(m[4]||'1')
  const bgRgb = hexToRgb(bg)
  const r = Math.round(parseInt(m[1])/255*a*255 + bgRgb.r*255*(1-a))
  const g2 = Math.round(parseInt(m[2])/255*a*255 + bgRgb.g*255*(1-a))
  const b2 = Math.round(parseInt(m[3])/255*a*255 + bgRgb.b*255*(1-a))
  return '#'+[r,g2,b2].map(x=>x.toString(16).padStart(2,'0')).join('')
}

// ── Pairs to check ────────────────────────────────────────────────────────────
const PAIRS = [
  // label, text-hex, bg-hex, AA body (4.5), large text/UI (3.0)
  ['ink on bg (body)',            TOKENS.ink,     TOKENS.bg,       4.5],
  ['ink on surface (body)',       TOKENS.ink,     TOKENS.surface,  4.5],
  ['ink on surface-2 (body)',     TOKENS.ink,     TOKENS.surface2, 4.5],
  ['ink-muted on bg (body)',      blendOnBg(TOKENS.inkMuted, TOKENS.bg), TOKENS.bg, 4.5],
  ['on-accent on accent (btn)',   TOKENS.onAccent,TOKENS.accent,   4.5],
  ['ok on ok-bg',                 TOKENS.ok,      '#E8F5EC',       4.5],
  ['warn on warn-bg',             TOKENS.warn,    '#FFF3D6',       4.5],
  ['danger on danger-bg',         TOKENS.danger,  '#FDEAEA',       4.5],
  // Dark theme
  ['dark: ink on bg',             TOKENS.dark_ink,TOKENS.dark_bg,  4.5],
  ['dark: ink on surface',        TOKENS.dark_ink,TOKENS.dark_surface, 4.5],
  ['dark: on-accent on accent',   TOKENS.onAccent,TOKENS.accent,   4.5],
  // Forbidden: marigold text on light BG – should NOT appear in codebase
  // These are not "pairs we use" but checks we document as forbidden
  ['FORBIDDEN: accent on bg',     TOKENS.accent,  TOKENS.bg,       99],   // should FAIL (high threshold = always fail)
  ['FORBIDDEN: accent on surface',TOKENS.accent,  TOKENS.surface,  99],
]

let md = '# DentSloth Contrast Report\n\nGenerated by `scripts/check_contrast.mjs`\n\nTarget: WCAG AA (4.5:1 body, 3.0:1 large/UI).\n\n'
md += '| Pair | Ratio | Required | Status |\n|---|---|---|---|\n'

let failures = 0
for (const [label, text, bg, required] of PAIRS) {
  let ratio
  try { ratio = contrast(text, bg) } catch { ratio = 0 }
  const pass = ratio >= required
  if (!pass && required < 10) failures++   // don't count "forbidden" as failures
  const isForbidden = required >= 10
  const status = isForbidden
    ? (ratio < 3 ? '⛔ FORBIDDEN (correct – never use)' : '🚨 FORBIDDEN COLOR USED AS TEXT')
    : (pass ? '✅ Pass' : '❌ Fail')
  md += `| ${label} | ${ratio.toFixed(2)}:1 | ${required < 10 ? required+':1' : 'Not used'} | ${status} |\n`
}

md += `\n**${failures} failures.**\n`
if (failures === 0) md += 'All required token pairs meet WCAG AA.\n'
else md += '⚠️ Fix the failing pairs before shipping.\n'

const outDir = join(__dirname,'..','docs')
mkdirSync(outDir,{recursive:true})
writeFileSync(join(outDir,'contrast.md'), md)
console.log(md)
console.log(failures === 0 ? '\n✅ All contrast checks passed.' : `\n❌ ${failures} contrast failures.`)
process.exit(failures)
