#!/usr/bin/env python3
"""
Generate synthetic price history CSV for TabPFN training.
ALL DATA IS SYNTHETIC. Label says so in header. Do not use as real market data.
Run: python scripts/generate_seed_prices.py
Output: data/price_history.csv (~600 rows)
"""
import random, csv, math, os
from pathlib import Path

random.seed(42)

INSTRUMENT_TYPES = [
    "mouth_mirror","dental_probe","periodontal_probe","college_tweezers",
    "sickle_scaler","gracey_curette","universal_curette","ultrasonic_tip",
    "extraction_forceps_upper_anterior","extraction_forceps_upper_molar",
    "extraction_forceps_lower_molar","dental_elevator_straight","periosteal_elevator",
    "composite_instrument_set","amalgam_carrier","amalgam_condenser","burnisher_ball",
    "carver_cleoid_discoid","weingart_plier","bird_beak_plier","handpiece_highspeed",
    "handpiece_lowspeed","ultrasonic_scaler_unit","shade_guide","rubber_dam_forceps",
    "rubber_dam_frame","mouth_prop","bone_file","needle_holder","tissue_scissors",
]

BRAND_TIERS = {
    "premium": {"brands": ["Hu-Friedy","Kohler","NSK","W&H","KaVo"], "multiplier": 1.4},
    "midrange": {"brands": ["GDC","Dentsply","SS White","Miltex","Nordent"], "multiplier": 1.0},
    "economy":  {"brands": ["Generic","House Brand","LocalMake","Budget Plus"], "multiplier": 0.6},
}

CONDITION_GRADE_FACTOR = {"A": 0.80, "B": 0.60, "C": 0.40}

NEW_PRICE_RANGES = {
    "mouth_mirror": (150, 800), "dental_probe": (120, 600),
    "periodontal_probe": (200, 900), "college_tweezers": (100, 500),
    "sickle_scaler": (200, 1200), "gracey_curette": (300, 1800),
    "universal_curette": (300, 1600), "ultrasonic_tip": (400, 3000),
    "extraction_forceps_upper_anterior": (500, 2500),
    "extraction_forceps_upper_molar": (600, 3000),
    "extraction_forceps_lower_molar": (600, 3000),
    "dental_elevator_straight": (300, 1500), "periosteal_elevator": (300, 1800),
    "composite_instrument_set": (800, 4000), "amalgam_carrier": (400, 2000),
    "amalgam_condenser": (200, 1200), "burnisher_ball": (150, 800),
    "carver_cleoid_discoid": (200, 1000), "weingart_plier": (600, 3000),
    "bird_beak_plier": (500, 2500), "handpiece_highspeed": (3000, 25000),
    "handpiece_lowspeed": (2000, 15000), "ultrasonic_scaler_unit": (5000, 40000),
    "shade_guide": (1500, 8000), "rubber_dam_forceps": (600, 3000),
    "rubber_dam_frame": (200, 1000), "mouth_prop": (150, 700),
    "bone_file": (300, 1500), "needle_holder": (400, 2500),
    "tissue_scissors": (300, 1500),
}

def depreciation_factor(age_years: float) -> float:
    """Rapid first-year drop, then slower decay, floor at 0.15."""
    return max(0.15, math.exp(-0.22 * age_years))

rows = []
for _ in range(600):
    itype = random.choice(INSTRUMENT_TYPES)
    tier_name = random.choices(["premium","midrange","economy"], weights=[2,5,3])[0]
    tier = BRAND_TIERS[tier_name]
    brand = random.choice(tier["brands"])
    condition = random.choices(["A","B","C"], weights=[2,5,3])[0]
    age = round(random.uniform(0.5, 12.0), 1)
    cycles = int(age * random.uniform(20, 80))

    lo, hi = NEW_PRICE_RANGES.get(itype, (200, 2000))
    orig = round(random.uniform(lo, hi) * tier["multiplier"], -1)

    dep = depreciation_factor(age)
    cond_f = CONDITION_GRADE_FACTOR[condition]
    noise = random.gauss(1.0, 0.08)
    sale_price = round(max(50, orig * dep * cond_f * noise), -1)

    rows.append({
        "instrument_type": itype,
        "brand": brand,
        "brand_tier": tier_name,
        "condition_grade": condition,
        "age_years": age,
        "sterilization_cycles_est": cycles,
        "original_price_inr": orig,
        "sale_price_inr": sale_price,
    })

out = Path(__file__).parent.parent / "data" / "price_history.csv"
out.parent.mkdir(parents=True, exist_ok=True)
fieldnames = list(rows[0].keys())

with open(out, "w", newline="", encoding="utf-8") as f:
    f.write("# SYNTHETIC DATA – generated by DentSloth scripts/generate_seed_prices.py – NOT real market data\n")
    writer = csv.DictWriter(f, fieldnames=fieldnames)
    writer.writeheader()
    writer.writerows(rows)

print(f"Generated {len(rows)} synthetic rows -> {out}")
